// Last resort when the lookup is blocked: the browser's own time zone name.
export function zoneGuess() {
  let tz = "";
  try { tz = Intl.DateTimeFormat().resolvedOptions().timeZone || ""; } catch { /* no Intl */ }
  const hit = ZONES[tz];
  if (hit) return { lat: hit[0], lon: hit[1], city: hit[2], country: hit[3], isp: "", approx: true };
  const off = -new Date().getTimezoneOffset() / 60;
  const city = (tz.split("/").pop() || "your city").replace(/_/g, " ");
  return { lat: 28, lon: off * 15, city, country: "", isp: "", approx: true };
}

