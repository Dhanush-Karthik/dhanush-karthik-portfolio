export const MASK_W = 1440;
export const MASK_H = 720;

let maskCache = null;
// Equirectangular mask: white land, black sea. Row 0 is +90 degrees.
export function buildMask() {
  if (maskCache) return maskCache;
  const c = document.createElement("canvas");
  c.width = MASK_W; c.height = MASK_H;
  const ctx = c.getContext("2d", { willReadFrequently: true });
  ctx.fillStyle = "#000"; ctx.fillRect(0, 0, MASK_W, MASK_H);
  const X = (lon) => ((lon + 180) / 360) * MASK_W;
  const Y = (lat) => ((90 - lat) / 180) * MASK_H;
  const poly = (pts, color) => {
    ctx.fillStyle = color; ctx.beginPath();
    pts.forEach(([lo, la], i) => (i ? ctx.lineTo(X(lo), Y(la)) : ctx.moveTo(X(lo), Y(la))));
    ctx.closePath(); ctx.fill();
  };
  LAND.forEach((p) => poly(p, "#fff"));
  SEAS.forEach((p) => poly(p, "#000"));
  const data = ctx.getImageData(0, 0, MASK_W, MASK_H).data;
  const tex = new THREE.CanvasTexture(c);
  tex.colorSpace = THREE.NoColorSpace;
  tex.minFilter = THREE.LinearMipmapLinearFilter;
  tex.anisotropy = 4;
  maskCache = {
    canvas: c,
    tex,
    land: (lat, lon) => {
      const x = Math.min(MASK_W - 1, Math.max(0, Math.floor(((lon + 180) / 360) * MASK_W)));
      const y = Math.min(MASK_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * MASK_H)));
      return data[(y * MASK_W + x) * 4] > 127;
    },
  };
  return maskCache;
}

// ---- spherical helpers (globe radius 1, y up) ----
const D2R = Math.PI / 180;
export const toVec = (lat, lon, r = 1, out = new THREE.Vector3()) => {
  const la = lat * D2R, lo = lon * D2R;
  return out.set(Math.cos(la) * Math.cos(lo) * r, Math.sin(la) * r, -Math.cos(la) * Math.sin(lo) * r);
};
export const toLatLon = (v) => ({ lat: Math.asin(THREE.MathUtils.clamp(v.y / v.length(), -1, 1)) / D2R, lon: Math.atan2(-v.z, v.x) / D2R });

// Local frame at a point on the globe: east, up (normal) and north tangents.
export function frameAt(n, out = {}) {
  const up = (out.up || new THREE.Vector3()).copy(n).normalize();
  const east = (out.east || new THREE.Vector3()).set(0, 1, 0).cross(up);
  if (east.lengthSq() < 1e-8) east.set(1, 0, 0);
  east.normalize();
  const north = (out.north || new THREE.Vector3()).copy(up).cross(east).normalize();
  out.up = up; out.east = east; out.north = north;
  return out;
}

// Move along the surface from a point by a tangent direction and a distance (radians).
export function walk(from, dir, dist, out = new THREE.Vector3()) {
  const n = from.clone().normalize();
  const t = dir.clone().addScaledVector(n, -dir.dot(n)).normalize();
  return out.copy(n).multiplyScalar(Math.cos(dist)).addScaledVector(t, Math.sin(dist)).normalize();
}

export function gcAngle(a, b) {
  return Math.acos(THREE.MathUtils.clamp(a.clone().normalize().dot(b.clone().normalize()), -1, 1));
}

// Dot-matrix land: a ring-per-latitude grid, kept where the mask says land.
export function landDots(step = 1.35) {
  const mask = buildMask();
  const pts = [];
  for (let lat = -84; lat <= 84; lat += step) {
    const n = Math.max(1, Math.round((360 * Math.cos(lat * D2R)) / step));
    for (let i = 0; i < n; i++) {
      const lon = -180 + ((i + (Math.round((lat + 90) / step) % 2) * 0.5) / n) * 360;
      if (mask.land(lat, lon)) { const v = toVec(lat, lon, 1.0015); pts.push(v.x, v.y, v.z); }
    }
  }
  return new Float32Array(pts);
}

